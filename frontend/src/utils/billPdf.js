import { PdfDocument, PDF_PAGE, clean } from './pdfWriter.js';
import { billStatus, isPastDue } from './billMath.js';
import { dayKey } from './expenseMath.js';

const STATUS_LABEL = { upcoming: 'Unpaid', dueToday: 'Due today', overdue: 'Overdue', partial: 'Partially paid', paid: 'Paid', cancelled: 'Cancelled' };
const FREQUENCY_LABEL = { daily: 'Daily', weekly: 'Weekly', monthly: 'Monthly', quarterly: 'Quarterly', yearly: 'Yearly' };

const formatDay = (value) => {
  if (!value) return '-';
  return new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(new Date(`${dayKey(value)}T00:00:00Z`));
};

const formatAmount = (value, currency) => {
  try {
    return new Intl.NumberFormat('en-US', { style: 'currency', currency, currencyDisplay: 'code', minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(value).replace(/ /g, ' ');
  } catch (error) {
    return `${currency} ${Number(value).toFixed(2)}`;
  }
};

const sourceOf = (method, name) => {
  if (!method) return '-';
  if (method === 'cash') return 'Cash';
  return name || '-';
};

export const buildBillDocument = (bill, { categoryName = '', today }) => {
  const status = billStatus(bill, today);
  const kind = status === 'paid' ? 'receipt' : status === 'partial' ? 'summary' : 'bill';
  const money = (value) => formatAmount(value, bill.currency);
  const payments = [...bill.payments]
    .sort((a, b) => dayKey(a.paidAt).localeCompare(dayKey(b.paidAt)))
    .map((payment) => ({ date: formatDay(payment.paidAt), amount: money(payment.amount), source: sourceOf(payment.payMethod, payment.payName), note: payment.note || '' }));
  const last = bill.payments.length ? [...bill.payments].sort((a, b) => dayKey(b.paidAt).localeCompare(dayKey(a.paidAt)))[0] : null;

  const details = [
    ['Company', bill.billerName],
    ['Account number', bill.billerAccount || '-'],
    ['Category', categoryName || 'Other'],
    ['Billing period', bill.periodStart && bill.periodEnd ? `${formatDay(bill.periodStart)} to ${formatDay(bill.periodEnd)}` : '-'],
    ['Due date', formatDay(bill.dueAt)],
  ];
  if (bill.frequency !== 'none') details.push(['Repeats', FREQUENCY_LABEL[bill.frequency]]);
  if (kind === 'receipt' && last) {
    details.push(['Payment date', formatDay(last.paidAt)]);
    details.push(['Payment source', sourceOf(last.payMethod, last.payName)]);
  }

  const amounts = [['Bill amount', money(bill.amount)]];
  if (bill.installation > 0) amounts.push(['Installation charges', money(bill.installation)]);
  amounts.push(['Total', money(bill.total)]);
  if (kind === 'bill') amounts.push(['Amount due', money(bill.remaining), true]);
  else {
    amounts.push(['Amount paid', money(bill.paid)]);
    amounts.push([kind === 'receipt' ? 'Balance' : 'Remaining balance', money(bill.remaining), true]);
  }

  return {
    kind,
    title: kind === 'receipt' ? 'PAYMENT RECEIPT' : kind === 'summary' ? 'PAYMENT SUMMARY' : 'BILL',
    reference: `BILL-${String(bill.id).slice(-6).toUpperCase()}`,
    status: isPastDue(bill, today) && status === 'partial' ? 'Partially paid, overdue' : STATUS_LABEL[status],
    statusKey: status,
    biller: bill.billerName,
    billerId: bill.billerId,
    details,
    amounts,
    payments,
    generated: `Generated by Vaultrix on ${formatDay(today)}`,
    fileName: `${clean(bill.billerName).replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase() || 'bill'}-${kind === 'receipt' ? 'receipt' : kind === 'summary' ? 'payment-summary' : 'bill'}.pdf`,
  };
};

export const renderBillPdf = (doc) => {
  const pdf = new PdfDocument();
  const left = pdf.margin;
  const right = PDF_PAGE.width - pdf.margin;
  const inner = right - left;

  pdf.rect(0, 0, PDF_PAGE.width, 118, { fill: '#111114' });
  pdf.text('VAULTRIX', left, 62, { size: 22, bold: true, fill: '#ffffff' });
  pdf.text(doc.title, right, 56, { size: 13, bold: true, fill: '#ffffff', align: 'right' });
  pdf.text(doc.reference, right, 74, { size: 9, fill: '#c9c9d1', align: 'right' });
  pdf.y = 150;

  pdf.text(doc.biller, left, pdf.y + 8, { size: 20, bold: true });
  const badge = doc.status;
  const badgeWidth = pdf.width(badge, 9, true) + 20;
  pdf.rect(right - badgeWidth, pdf.y - 8, badgeWidth, 22, { fill: doc.statusKey === 'paid' ? '#111114' : '#ffffff', stroke: '#111114', lineWidth: 1 });
  pdf.text(badge, right - badgeWidth / 2, pdf.y + 7, { size: 9, bold: true, fill: doc.statusKey === 'paid' ? '#ffffff' : '#111114', align: 'center' });
  pdf.y += 38;

  pdf.text('DETAILS', left, pdf.y, { size: 8, bold: true, fill: '#6b6b70' });
  pdf.y += 10;
  doc.details.forEach(([label, value]) => {
    const lines = pdf.wrap(value, 10, true, inner * 0.6);
    const height = Math.max(26, lines.length * 13 + 12);
    pdf.ensure(height);
    pdf.line(left, pdf.y, right);
    pdf.text(label, left, pdf.y + 17, { size: 10, fill: '#6b6b70' });
    lines.forEach((line, index) => pdf.text(line, right, pdf.y + 17 + index * 13, { size: 10, bold: true, align: 'right' }));
    pdf.y += height;
  });
  pdf.line(left, pdf.y, right);
  pdf.y += 26;

  const boxHeight = doc.amounts.length * 26 + 22;
  pdf.ensure(boxHeight + 20);
  pdf.rect(left, pdf.y, inner, boxHeight, { fill: '#f7f7f8', stroke: '#e5e5e7' });
  let rowY = pdf.y + 26;
  doc.amounts.forEach(([label, value, strong]) => {
    pdf.text(label, left + 16, rowY, { size: strong ? 12 : 10, bold: Boolean(strong), fill: strong ? '#111114' : '#6b6b70' });
    pdf.text(value, right - 16, rowY, { size: strong ? 14 : 10, bold: true, align: 'right' });
    rowY += 26;
  });
  pdf.y += boxHeight + 28;

  if (doc.payments.length > 0) {
    pdf.ensure(60);
    pdf.text('PAYMENT HISTORY', left, pdf.y, { size: 8, bold: true, fill: '#6b6b70' });
    pdf.y += 12;
    const columns = { date: left, source: left + 100, note: left + 230, amount: right };
    const header = () => {
      pdf.rect(left, pdf.y, inner, 22, { fill: '#111114' });
      pdf.text('Date', columns.date + 8, pdf.y + 15, { size: 9, bold: true, fill: '#ffffff' });
      pdf.text('Source', columns.source, pdf.y + 15, { size: 9, bold: true, fill: '#ffffff' });
      pdf.text('Note', columns.note, pdf.y + 15, { size: 9, bold: true, fill: '#ffffff' });
      pdf.text('Amount', columns.amount - 8, pdf.y + 15, { size: 9, bold: true, fill: '#ffffff', align: 'right' });
      pdf.y += 22;
    };
    header();
    doc.payments.forEach((payment, index) => {
      const sourceLines = pdf.wrap(payment.source, 9, false, 124);
      const noteLines = pdf.wrap(payment.note || '-', 9, false, right - columns.note - 110);
      const rows = Math.max(sourceLines.length, noteLines.length);
      const height = rows * 12 + 12;
      if (pdf.y + height > PDF_PAGE.height - pdf.margin - 24) {
        pdf.newPage();
        header();
      }
      if (index % 2 === 1) pdf.rect(left, pdf.y, inner, height, { fill: '#f7f7f8' });
      pdf.text(payment.date, columns.date + 8, pdf.y + 15, { size: 9 });
      sourceLines.forEach((line, row) => pdf.text(line, columns.source, pdf.y + 15 + row * 12, { size: 9 }));
      noteLines.forEach((line, row) => pdf.text(line, columns.note, pdf.y + 15 + row * 12, { size: 9, fill: '#6b6b70' }));
      pdf.text(payment.amount, columns.amount - 8, pdf.y + 15, { size: 9, bold: true, align: 'right' });
      pdf.y += height;
    });
    pdf.line(left, pdf.y, right);
    pdf.y += 24;
  }

  pdf.ensure(30);
  pdf.text(doc.generated, left, pdf.y + 10, { size: 8, fill: '#6b6b70' });
  return pdf.build();
};

export const billShareText = (doc) => {
  const lines = [`${doc.title} - ${doc.biller}`, `Status: ${doc.status}`, ...doc.details.filter(([label]) => ['Account number', 'Due date', 'Payment date'].includes(label) && true).map(([label, value]) => `${label}: ${value}`)];
  doc.amounts.forEach(([label, value]) => lines.push(`${label}: ${value}`));
  lines.push('', doc.generated);
  return lines.join('\n');
};

export const pdfFile = (doc) => new File([renderBillPdf(doc)], doc.fileName, { type: 'application/pdf' });
